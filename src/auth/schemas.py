from pydantic import BaseModel
from pydantic import Field


class SchemaTokenAccess(BaseModel):
    access: str = Field(..., example="ey0x0x0x0x0x0x0x0x0x0x0x0x0x0x0x0x0x0")
    refresh: str = Field(..., example="ey0x0x0x0x0x0x0x0x0x0x0x0x0x0x0x0x0x0")

    class Config:
        orm_mode = True


class SchemaTokenRefresh(BaseModel):
    refresh: str = Field(..., example="ey0x0x0x0x0x0x0x0x0x0x0x0x0x0x0x0x0x0")


class SchemaLogin(BaseModel):
    email: str = Field(..., example="email@mail.com")
    password: str = Field(..., example="password")
