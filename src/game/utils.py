import json

from sqlalchemy.orm import Session

from gpt_ai.utils import generate_gpt4_
from prompt.services import get_prompt_by_field

from category.schemas import SchemaRetrieveCategory


def get_history(db: Session, story_line: str):
    prompt_history = get_prompt_by_field(db, 'category', 'history')

    schema_story = {
        "title": "string (title of the story)",
        "general_content": "string (general content of the story)",
        "chapters": [
            {
                "name": "string (name of the chapter)",
                "content": "string (content of the chapter)"
            }
        ],
        "chapter": [
            {
                "number": "string (number of the chapter)",
                "name": "string (name of the chapter)",
                "content": "string (content of the chapter)",
                "scenes": [
                    {
                        "number": "string (number of the scene)",
                        "name": "string (name of the scene)",
                        "content": "string (content of the scene)",
                        "location": "string (location of the scene)"
                    }
                ]
            }
        ]
    }
    text_user = prompt_history.description.replace('x_story_line', story_line)

    content_prompt = [
        {
            "role": "system",
            "content": f"cada escena de cada capitulo debe ser variada,"
                       f"logra que el primer capitulo sea el mas interesante,"
                       f"logra que el primer capitulo tenga una escena de dialogo, una de busqueda, una de entrega y una de batalla,"
                       f"logra que el primer primer capitulo tenga un personaje principal, un antagonista, un  o un mini enemigo"
                       f"y un mini enemigo que pueden ser un ave negra o un zorro marron, "
                       f"{prompt_history.prompt_system} "
                       f"responde con un JSON que contenga el esquema '{schema_story}'"
        },
        {
            "role": "user",
            "content": [
                {
                    "type": "text",
                    "text": text_user
                }
            ]
        }
    ]

    history_generated = generate_gpt4_(content_prompt=content_prompt,
                                       type_text="history",
                                       max_tokens=4096)

    return json.loads(history_generated)


def get_synopsis(db: Session, history: dict) -> dict:
    prompt_synopsis = get_prompt_by_field(db, 'category', 'synopsis')

    schema_synopsis = {
        "synopsis_generate": "string ( this is a synopsis generated by the AI)",
        "title": "string (title of the game)",
        "prompt_image": "string (create a prompt to create an image containing the story of the game )",
        "summary": "string (summary of the game to be a maximum of 4 lines, in continuous narrative form without "
                   "listing the chapters, narrated by a narrator.)"

    }

    content_prompt = [
        {
            "role": "system",
            "content": f"{prompt_synopsis.prompt_system} "
                       f"responde con un JSON que contenga el esquema '{schema_synopsis}'"
        },
        {
            "role": "assistant",
            "content": f"historia del juego :{history}"

        },
        {
            "role": "user",
            "content": [
                {
                    "type": "text",
                    "text": prompt_synopsis.description
                }
            ]
        }
    ]

    synopsis_generated = generate_gpt4_(content_prompt=content_prompt,
                                        type_text="synopsis",
                                        max_tokens=4096, )

    return json.loads(synopsis_generated)


