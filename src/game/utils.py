async def number_players_have_played_game_util(game_id: str):
    pipeline = [
        {"$match": {"game_id": game_id}},
        {"$group": {"_id": "$user_id"}},
        {"$count": "distinct_user_count"},
    ]
    result = await db['record_game'].aggregate(pipeline).to_list(None)
    if result:
        distinct_user_count = result[0]["distinct_user_count"]
    else:
        distinct_user_count = 0

    return distinct_user_count


async def last_date_played_game_util(game_id: str, user_id: str):
    pipeline = [
        {"$match": {"game_id": game_id}},
        {"$sort": {"created_at": -1}},
        {"$limit": 1},
    ]
    result = await db['record_game'].aggregate(pipeline).to_list(None)
    if result:
        last_date_played = result[0]["created_at"]
    else:
        last_date_played = None

    return last_date_played


async def get_first_5_records_by_user(user_id: str):
    pipeline = [
        {"$match": {"user_id": user_id}},
        {"$sort": {"created_at": -1}},
        {"$group": {"_id": "$game_id", "latest_record": {"$first": "$$ROOT"}}},
        {"$replaceRoot": {"newRoot": "$latest_record"}},
        {"$sort": {"created_at": -1}},  # Add a second sort after grouping
        {"$limit": 5},
    ]
    result = await db['record_game'].aggregate(pipeline).to_list(None)
    return result
