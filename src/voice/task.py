import random

from bson import ObjectId
from pydantic import BaseModel, Field

from core.database import db
from gpt_ai.utils import openai_generator
from task.services import update_task_service
from voice.elevenlabs import generate_audio
from voice.services import get_variants_service


class SchemaVoiceIdentification(BaseModel):
    age: str = Field(..., description="Age of the voice according to the description")
    genre: str = Field(..., description="Genre of the voice according to the description")


class SchemaDialogue(BaseModel):
    dialogue: str = Field(..., description="Dialogue generated by the AI")


async def generate_voice_character(character_id: str, user_id: str):
    try:
        character_db = await db["character"].find_one({"_id": ObjectId(character_id)})

        variants_voices = await get_variants_service()

        response_generated = await openai_generator.generate_gpt(
            content_prompt=[
                {
                    "role": "system",
                    "content": "Utilizando la siguiente descripción, identificar la voz que mejor se ajuste a la descripción. "
                               f"Respondiendo con la edad y género de la voz,"
                },
                {
                    "role": "assistant",
                    "content": f"Variantes de voces a identificar: {variants_voices}"
                },
                {
                    "role": "user",
                    "content": f"Descripción del personaje: {character_db['description']}"
                               f"Genero del personaje: {character_db['genre']}"
                }
            ],
            response_format=SchemaVoiceIdentification,
            type_generation="Voice Identification",
            max_tokens=2000,
            model="gpt-4o-mini",
            user_id=user_id
        )

        voice_by_gender = await db["voice"].find({"gender": response_generated["genre"]}).to_list(None)

        voice_by_age = [voice for voice in voice_by_gender if voice["age"] == response_generated["age"]]

        if voice_by_age:
            voice = voice_by_age[0]
        else:
            voice = random.choice(voice_by_gender)

        # if character["audio"]:
        #     delete_image(character["audio"])

        game_db = await db["game"].find_one({'characters_id': {'$in': [str(character_id)]}})

        if character_id == game_db["character_principal"]:
            content_prompt = [
                {
                    "role": "system",
                    "content": "You are a creative dialogue generator in english."},
                {
                    "role": "user",
                    "content": f"Generate a first-person text in english about of the character '{character_db['name']}' in the game '{game_db['title']}'. "
                               f"The current story is: {game_db['history']}. The character is described as: {character_db['prompt_user']}. "
                               f"don't use the “as a”, just say what it does and that's all, use the “I am” or “I will do”. "
                               f"do not physically describe the character,"
                               f"the dialogue can be a sentence, a question or statement in the interaction."
                               f"you are the protagonist, introduce yourself, what are you going to do?"
                               f"should be a maximum of 20 words. "
                }
            ]
            story = openai_generator.generate_gpt(
                content_prompt=content_prompt,
                max_tokens=2000,
                model="gpt-4o-mini",
                type_generation="Character Dialogue",
                user_id=user_id,
                response_format=SchemaDialogue
            )

            await db['character'].update_one({'_id': ObjectId(character_id)},
                                             {'$set': {'presentation': story.dialogue}})
        else:
            content_prompt = [
                {
                    "role": "system",
                    "content": "You are a creative dialogue generator in english."},
                {
                    "role": "user",
                    "content": f"Generate a first-person text in english about of the character '{character_db['name']}' in the game '{game_db['title']}'. "
                               f"The current story is: {game_db['history']}. The character is described as: {character_db['prompt_user']}. "
                               f"the dialogue should be the response of the interaction between that character and the main character."
                               f"do not physically describe the character,"
                               f" the dialogue can be a sentence, a question or statement in the interaction you have with the character"
                               f"should be a maximum of 20 words. "
                }
            ]
            story = openai_generator.generate_gpt(
                content_prompt=content_prompt,
                max_tokens=2000,
                model="gpt-4o-mini",
                type_generation="Character Dialogue",
                user_id=user_id,
                response_format=SchemaDialogue
            )
            await db['character'].update_one({'_id': ObjectId(character_id)},
                                             {'$set': {'presentation': story.dialogue}})

        voice_url = generate_audio(text=story['dialogue'],
                                   voice_id=voice["voice_id"])

        await db["character"].update_one({"_id": ObjectId(character_id)},
                                         {"$set": {"audio": voice_url}})

        return True
    except Exception as e:
        print(f"Error in generate voice service: {str(e)}")
        return False


async def async_generate_voice_task(_character_id: str, _user_id: str, _task_id: str):

    await update_task_service(
        _id=_task_id,
        _status="pending"
    )

    character_db = await db["character"].find_one({"_id": ObjectId(_character_id)})
    if not character_db:
        await update_task_service(
            _id=_task_id,
            _status="failed",
            _message=f"Error can't find character with id {_character_id}"
        )
        return "Error can't find character"
    voice_generated = await generate_voice_character(_character_id, _user_id)
    if not voice_generated:
        await update_task_service(
            _id=_task_id,
            _status="failed",
            _message="Error voice not generated"
        )
        return "Error voice not generated"
    await update_task_service(
        _id=_task_id,
        _status="completed",
        _message="Voice character generated"
    )
    return "Voice character generated"